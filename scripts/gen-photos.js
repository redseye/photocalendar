// Scans dayphoto/ and writes src/photos.generated.ts with a static require() map
// (Metro can only bundle images referenced by static require calls).
// Usage: npm run gen-photos
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const photoDir = path.join(root, 'dayphoto');
const outFile = path.join(root, 'src', 'photos.generated.ts');

function isValidDate(key) {
  const y = Number(key.slice(0, 4));
  const m = Number(key.slice(4, 6));
  const d = Number(key.slice(6, 8));
  const date = new Date(Date.UTC(y, m - 1, d));
  return (
    date.getUTCFullYear() === y &&
    date.getUTCMonth() === m - 1 &&
    date.getUTCDate() === d
  );
}

const keys = fs
  .readdirSync(photoDir)
  .filter((name) => /^\d{8}\.jpg$/.test(name))
  .map((name) => name.slice(0, 8))
  .filter(isValidDate)
  .sort();

const lines = [
  '// Generated by scripts/gen-photos.js (npm run gen-photos). Do not edit by hand.',
  "import type { ImageRequireSource } from 'react-native';",
  '',
  'export const photos: Record<string, ImageRequireSource> = {',
  ...keys.map((key) => `  '${key}': require('../dayphoto/${key}.jpg'),`),
  '};',
  '',
];

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, lines.join('\n'), 'utf8');
console.log(`Wrote ${keys.length} photo entries to ${path.relative(root, outFile)}`);
